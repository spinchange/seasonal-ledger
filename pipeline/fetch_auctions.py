"""Fetch Treasury's tentative auction schedule -> planner/<year>/treasury_auctions.yaml.

Source: U.S. Treasury, Office of Debt Management, "Tentative Auction Schedule of U.S.
Treasury Securities" (XML), republished at each quarterly refunding (early Feb, May, Aug,
Nov). Each release covers roughly the next six months, so a year's calendar fills in over
several refundings: re-run this after each one. Entries already in the YAML are kept, and
dates in the new release replace them from the release's first auction onward.

Only coupon securities are kept (notes, bonds, TIPS, FRNs); bills auction several times a
week and would bury the calendar. Public-domain government data, fine to commit.

Usage: python pipeline/fetch_auctions.py [year]
"""
from __future__ import annotations

import datetime as dt
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

URL = "https://home.treasury.gov/system/files/221/Tentative-Auction-Schedule.xml"
ROOT = Path(__file__).resolve().parents[1]


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):  # no &id001 anchors in a hand-readable file
        return True


def label(term: str, typ: str, tips: bool, frn: bool) -> str:
    n = term.split("-")[0]
    unit = "yr" if term.endswith("Year") else "wk"
    kind = "TIPS" if tips else "FRN" if frn else typ.lower()
    return f"{n}-{unit} {kind}"


def main():
    year = int(sys.argv[1]) if len(sys.argv) > 1 else 2027
    out = ROOT / "planner" / str(year) / "treasury_auctions.yaml"
    req = urllib.request.Request(URL, headers={"User-Agent": "seasonal-ledger-build"})
    root = ET.fromstring(urllib.request.urlopen(req, timeout=60).read())
    name = root.findtext("AuctionCalendarName")
    new = []
    for a in root.findall("AuctionCalendarDate"):
        typ, d = a.findtext("SecurityType"), a.findtext("AuctionDate")
        if not typ or typ == "BILL" or not d or not d.startswith(str(year)):
            continue
        new.append({"date": dt.date.fromisoformat(d),
                    "security": label(a.findtext("SecurityTermWeekYear"), typ,
                                      a.findtext("TIPS") == "Y", a.findtext("FloatingRate") == "Y"),
                    "reopening": a.findtext("ReOpeningIndicator") == "Y"})
    if not new:
        sys.exit(f"{name}: no {year} coupon auctions in this release; nothing written")
    new.sort(key=lambda x: (x["date"], x["security"]))
    old = yaml.safe_load(out.read_text(encoding="utf-8")) if out.exists() else {}
    kept = [x for x in (old.get("auctions") or []) if x["date"] < new[0]["date"]]
    releases = [r for r in (old.get("releases") or []) if r["name"] != name]
    releases.append({"name": name, "fetched": dt.date.today(), "first": new[0]["date"], "last": new[-1]["date"]})
    doc = {"source": URL,
           "note": "Generated by pipeline/fetch_auctions.py; re-run after each quarterly refunding. "
                   "Coupon auctions only (no bills). Dates are Treasury's tentative schedule.",
           "covered_through": new[-1]["date"],
           "releases": releases,
           "auctions": kept + new}
    out.write_text("# " + doc["note"] + "\n" + yaml.dump(doc, Dumper=Dumper, sort_keys=False, allow_unicode=True),
                   encoding="utf-8", newline="\n")
    print(f"{name}: {len(new)} coupon auctions {new[0]['date']}..{new[-1]['date']} -> {out}")


if __name__ == "__main__":
    main()
